def _social_apps(provider):
    prefix = provider.upper()
    client_id = os.environ.get(f"{prefix}_CLIENT_ID")
    client_secret = os.environ.get(f"{prefix}_CLIENT_SECRET")
    if not client_id:
        return []
    return [{"client_id": client_id, "secret": client_secret or "", "key": ""}]


